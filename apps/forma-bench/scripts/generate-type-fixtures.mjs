import assert from "node:assert/strict";
import { mkdir, readFile, readdir, unlink, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import {
  fixtureFileName,
  providerCount,
  shapeKey,
  TYPE_SCALE_SHAPES,
} from "./type-scale-config.mjs";

const appRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const fixtureRoot = join(appRoot, "type-fixtures");
const mode = process.argv[2];

function nodeIdentifier(level, index) {
  return `NodeL${level}N${String(index).padStart(3, "0")}`;
}

function generateFixture(shape) {
  const { arity, depth } = shape;
  assert(Number.isInteger(arity) && arity > 1);
  assert(Number.isInteger(depth) && depth > 0);

  const lines = [
    "// Generated by scripts/generate-type-fixtures.mjs. Do not edit by hand.",
    'import { boundary, compose, ok } from "@xndrjs/forma";',
    "",
    `const TypeScale = boundary("type-scale-${shapeKey(shape)}");`,
    "",
  ];

  for (let level = 0; level <= depth; level += 1) {
    for (let index = 0; index < arity ** level; index += 1) {
      const node = nodeIdentifier(level, index);
      lines.push(
        `const ${node} = TypeScale.intent("node-l${level}-n${String(index).padStart(3, "0")}").contract<number, number, never>();`
      );
    }
  }

  for (let level = depth; level >= 0; level -= 1) {
    for (let index = 0; index < arity ** level; index += 1) {
      const node = nodeIdentifier(level, index);
      const provider = `${node}Provider`;
      lines.push("");

      if (level === depth) {
        lines.push(
          `const ${provider} = ${node}.provide.perContext().with(({ lifetime }) => {`,
          "  lifetime.onDispose(() => undefined);",
          "  return (input) => ok(input + 1);",
          "});"
        );
        continue;
      }

      const children = Array.from({ length: arity }, (_, childIndex) => ({
        key: `child${childIndex}`,
        intent: nodeIdentifier(level + 1, index * arity + childIndex),
      }));
      lines.push(`const ${provider} = ${node}.provide`);
      lines.push("  .using({");
      for (const child of children) {
        lines.push(`    ${child.key}: ${child.intent},`);
      }
      lines.push("  })", "  .with(({ deps }) => async (input) => {");
      for (const child of children) {
        lines.push(
          `    const ${child.key} = await deps.${child.key}(input);`,
          `    if (!${child.key}.ok) return ${child.key};`
        );
      }
      lines.push(
        `    return ok(${children.map((child) => `${child.key}.value`).join(" + ")});`,
        "  });"
      );
    }
  }

  lines.push(
    "",
    "export const typeScaleRoot = compose({",
    "  entryBoundaries: [TypeScale],",
    "  surface: { run: NodeL0N000Provider },",
    "  wiring: ["
  );
  for (let level = 1; level <= depth; level += 1) {
    for (let index = 0; index < arity ** level; index += 1) {
      lines.push(`    ${nodeIdentifier(level, index)}Provider,`);
    }
  }
  lines.push(
    "  ],",
    "});",
    "",
    `export const expectedProviderCount = ${providerCount(shape)};`,
    "export const typeScalePlan = typeScaleRoot.describePlan();",
    ""
  );

  return lines.join("\n");
}

if (mode !== "--write" && mode !== "--check") {
  throw new Error("Expected --write or --check.");
}

await mkdir(fixtureRoot, { recursive: true });
const expectedNames = new Set(TYPE_SCALE_SHAPES.map(fixtureFileName));

if (mode === "--write") {
  const existingNames = await readdir(fixtureRoot);
  for (const name of existingNames) {
    const isGeneratedFixture = /^(graph|tree)-.*\.ts$/.test(name);
    if (isGeneratedFixture && !expectedNames.has(name)) {
      await unlink(join(fixtureRoot, name));
    }
  }
}

for (const shape of TYPE_SCALE_SHAPES) {
  const path = join(fixtureRoot, fixtureFileName(shape));
  const expected = generateFixture(shape);

  if (mode === "--write") {
    await writeFile(path, expected);
    continue;
  }

  let actual;
  try {
    actual = await readFile(path, "utf8");
  } catch {
    throw new Error(`Missing generated type-scale fixture: ${path}`);
  }
  assert.equal(actual, expected, `Stale type-scale fixture: ${path}. Run pnpm generate.`);
}

console.log(
  mode === "--write"
    ? `Generated ${TYPE_SCALE_SHAPES.length} type-scale fixtures.`
    : `Verified ${TYPE_SCALE_SHAPES.length} type-scale fixtures.`
);
