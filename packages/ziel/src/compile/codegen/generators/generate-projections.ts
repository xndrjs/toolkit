/**
 * Projection codegen entry: checked `Program` → TypeScript source string.
 * Emits query-scoped projection types + memoized `project*` materializers.
 * Generated code imports runtime only from `@xndrjs/ziel`.
 *
 * Params / context types are assumed to already exist when this module is
 * composed after strategies; the focused entry emits types + projectors only.
 */
import type { Program } from "../../../ir";
import { emitProjectionTypes, emitProjections } from "../projections";

const GENERATED_HEADER = "/* Generated by @xndrjs/ziel/compile. Do not edit by hand. */";

const DEFAULT_IMPORT_FROM = "@xndrjs/ziel";
const DEFAULT_REGISTRY_TYPE_NAME = "ContentRegistry";

export type GenerateProjectionsOptions = {
  /** Module specifier for `ContentMap` import. Default: `@xndrjs/ziel`. */
  importFrom?: string;
  /** Name of the registry type used as the `ContentMap` generic. Default: `ContentRegistry`. */
  registryTypeName?: string;
  /**
   * Optional property name stamped with the resource name on projection shells
   * and types (e.g. `"$type"` or `"__resource"`). Default: unset (no stamp).
   */
  resourceTag?: string;
};

export type GenerateProjectionsResult = {
  /** Full TypeScript module source. */
  code: string;
};

type ResolvedOptions = {
  importFrom: string;
  registryTypeName: string;
  resourceTag: string | undefined;
};

function resolveOptions(options?: GenerateProjectionsOptions): ResolvedOptions {
  return {
    importFrom: options?.importFrom ?? DEFAULT_IMPORT_FROM,
    registryTypeName: options?.registryTypeName ?? DEFAULT_REGISTRY_TYPE_NAME,
    resourceTag: options?.resourceTag,
  };
}

function emitRuntimeImport(importFrom: string, program: Program): string {
  const symbols = ["type ContentMap"];
  if (program.queries.some((q) => q.projections.some((p) => p.resolveArms !== null))) {
    symbols.push("type ApplicationResourceIdentifier", "type ResourceKey");
  }
  return `import { ${symbols.join(", ")} } from ${JSON.stringify(importFrom)};`;
}

/**
 * Generate TypeScript source for query projection types and `project*` functions.
 *
 * Input should already be checked (`checkProgram` / `parseAndCheck`).
 * Output is a pure string (no filesystem writes). Params / context types are
 * not emitted here (see {@link generateStrategies} / compose).
 */
export function generateProjections(
  program: Program,
  options?: GenerateProjectionsOptions
): GenerateProjectionsResult {
  const { importFrom, registryTypeName, resourceTag } = resolveOptions(options);

  const bodyParts: string[] = [];

  const types = emitProjectionTypes(program, resourceTag);
  if (types.length > 0) {
    bodyParts.push(types);
  }

  const projectors = emitProjections(program, registryTypeName, resourceTag);
  if (projectors.length > 0) {
    bodyParts.push(projectors);
  }

  const parts: string[] = [GENERATED_HEADER];

  if (bodyParts.length > 0) {
    parts.push(emitRuntimeImport(importFrom, program));
    parts.push(...bodyParts);
  }

  return { code: `${parts.join("\n\n")}\n` };
}
